// Turns the exported web build (dist/) into an installable, offline iPhone web app.
// Usage: node scripts/make-pwa.mjs   (run after `expo export --platform web`)
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';
const base = (process.env.EXPO_BASE_URL || '').replace(/\/$/, ''); // e.g. "/watch-business-manager"
const indexPath = join(DIST, 'index.html');
if (!existsSync(indexPath)) throw new Error('dist/index.html not found — run `npx expo export --platform web` first');

// 1. Home-screen / full-screen tags for iPhone
let html = readFileSync(indexPath, 'utf8');
const head = `
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="Watch Business" />
    <meta name="theme-color" content="#0A0A0B" />
    <meta name="format-detection" content="telephone=no" />
    <link rel="manifest" href="${base}/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="${base}/icons/apple-touch-icon.png" />
    <style>html,body{background:#0A0A0B;overscroll-behavior:none}input,textarea{font-size:16px}*:focus{outline:none}</style>
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('${base}/sw.js', { scope: '${base}/' }).catch(function (e) { console.warn('SW', e); });
        });
      }
    </script>`;
html = html.replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, maximum-scale=1" />');
if (!html.includes('apple-mobile-web-app-capable')) html = html.replace('</head>', `${head}\n  </head>`);
writeFileSync(indexPath, html);

// 2. GitHub Pages: serve the app for any deep link, and don't hide the "_expo" folder
copyFileSync(indexPath, join(DIST, '404.html'));
writeFileSync(join(DIST, '.nojekyll'), '');

// 3. Offline: a service worker that pre-caches every file of this version
const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
const files = walk(DIST)
  .map((f) => relative(DIST, f).replace(/\\/g, '/'))
  .filter((f) => !['sw.js', '404.html', '.nojekyll', 'metadata.json'].includes(f));
const hash = createHash('sha256');
for (const f of files.sort()) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const urls = ['./', ...files.map((f) => `./${f}`)];

writeFileSync(
  join(DIST, 'sw.js'),
  `// Generated by scripts/make-pwa.mjs — version ${version}
const CACHE = 'watch-business-${version}';
const FILES = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('watch-business-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // App pages: always the cached app shell, so the app opens offline.
    e.respondWith(caches.match('./', { ignoreSearch: true }).then((r) => r || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((r) => r || fetch(req)));
});
`,
);
console.log(`PWA ready: ${files.length} files cached, version ${version}, base "${base || '/'}"`);
